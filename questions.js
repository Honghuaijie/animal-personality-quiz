const questions = [];
for (let round = 0; round < banks[0].length; round++) {
  banks.forEach((bank, axis) => {
    if (!bank[round]) return;
    const [prompt, ...labels] = bank[round].split("|");
    const rotation = (round + axis) % 4;
    const options = [0, 2, 1, 3].map(offset => {
      const index = (rotation + offset) % 4;
      return { label: labels[index], value: [2, 1, -1, -2][index] };
    });
    questions.push({ prompt, options, axis });
  });
}
